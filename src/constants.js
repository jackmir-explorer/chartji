function detectLocalCC(text){
  if(!text) return null;
  var found=[];
  CC_KEYWORDS.forEach(function(e){
    for(var i=0;i<e.kw.length;i++){
      if(text.includes(e.kw[i])){found.push(e.label);break;}
    }
  });
  return found.length>0?found.slice(0,2).join(" / "):null;
}

